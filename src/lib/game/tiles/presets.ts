import type { TerrainGrid } from "./types.js";

export interface GridPreset {
	id: string;
	name: string;
	grid: TerrainGrid;
}

function fromRows(rows: string[]): TerrainGrid {
	const width = rows[0].length;
	return {
		width,
		height: rows.length,
		cells: rows
			.join("")
			.split("")
			.map((cell) => (cell === "#" ? "path" : "grass")),
	};
}

